const getLogo = (
  variant: "outlined" | "filled",
  mainColor: "black" | "white",
) => {
  if (variant === "outlined") {
    if (mainColor === "black") return <LogoEmptyBlackStrokeWhite />;
    else return <LogoEmptyWhiteStrokeBlack />;
  } else {
    if (mainColor === "black") return <LogoFilledBlack />;
    else return <LogoFilledWhite />;
  }
};

const Logo = ({ variant = "filled", mainColor = "white" }: LogoProps) => {
  return getLogo(variant, mainColor);
};

export default Logo;
